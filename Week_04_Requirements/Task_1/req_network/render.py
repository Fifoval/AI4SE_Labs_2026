"""Deterministic node: render the final requirements document (Markdown + JSON)."""
import json
from datetime import date
from pathlib import Path

from .config import MODELS, PRIORITY_SCALE
from .llm import CACHED, CALLS
from .state import GraphState


def _blacklist(state: GraphState) -> list[dict]:
    by_cid = {c["cid"]: c for c in state["candidates"]}
    entries = []
    for it in state.get("rejected", []):
        entries.append({"name": it["name"], "statement": it["statement"],
                        "sources": [it["doc_id"]], "stage": f"Extraction ({it['status']})",
                        "reason": it["discard_reason"]})
    for code, res in state["area_results"].items():
        for d in res["discarded"]:
            cands = [by_cid[c] for c in d["candidate_ids"]]
            entries.append({"name": d["name"],
                            "statement": " / ".join(c["statement"] for c in cands),
                            "sources": sorted({c["doc_id"] for c in cands}),
                            "stage": f"Consolidation ({code})", "reason": d["reason"]})
    for b in state.get("conflict_blacklist", []):
        entries.append({"name": f"{b['name']} (was {b['id']})", "statement": b["description"],
                        "sources": b["sources"], "stage": "Conflict resolution",
                        "reason": b["reason"]})
    return [{**e, "id": f"BL-{i:03d}"} for i, e in enumerate(entries, 1)]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(state: GraphState) -> dict:
    docs = {d["doc_id"]: d for d in state["documents"]}
    reqs = state["requirements"]
    blacklist = _blacklist(state)
    open_issues = [{**t, "oid": f"OI-{i:03d}"} for i, t in enumerate(state.get("tensions", []), 1)]
    oi_of: dict[str, list[str]] = {}
    for t in open_issues:
        for x in t["ids"]:
            oi_of.setdefault(x, []).append(t["oid"])
    out = []
    w = out.append

    w("# Software Requirements Specification\n")
    w(f"*Generated by the requirements-refinement agentic network on {date.today():%Y-%m-%d} "
      f"from {len(docs)} input documents.*\n")

    w("## 1. Introduction\n")
    w("This document consolidates the requirements found in the input corpus. Each requirement "
      "has a unique identifier `REQ-<AREA>-<NNN>`, a short name, a descriptive paragraph, a "
      "priority and the list of source documents it was derived from (see Section 2 for the "
      "document identifiers). Requirements that were identified but discarded are listed in "
      "the blacklist (Section 6) together with the reason; tensions between kept requirements "
      "that need stakeholder clarification are listed as open issues (Section 7).\n")
    w("### 1.1 Priority scale\n")
    w("| Priority | Meaning |\n|---|---|")
    for k, v in PRIORITY_SCALE.items():
        w(f"| **{k}** | {v} |")
    w("\nPriority evidence is detected in the source text without AI: an explicit priority "
      "marker (e.g. `[* High Priority]`) in the paragraph of the quoted statement decides; "
      "otherwise the modal wording of the quote or of the nearest preceding sentence in the "
      "same paragraph. Statements without priority wording default to Should. A requirement "
      "can be Must only if at least one of its sources states it as mandatory, and an "
      "explicit high-priority marker always makes it Must.\n")
    w("### 1.2 Glossary\n")
    w("All requirements use the preferred terms below.\n")
    w("| Term | Definition | Avoided synonyms |\n|---|---|---|")
    for g in sorted(state["glossary"], key=lambda g: g["term"].lower()):
        w(f"| {_cell(g['term'])} | {_cell(g['definition'])} | {_cell(', '.join(g['synonyms_to_avoid']))} |")
    w("")

    w("## 2. Source documents\n")
    w("| ID | File | Type | Date | Authority | Notes |\n|---|---|---|---|---|---|")
    for d in docs.values():
        w(f"| {d['doc_id']} | `{d['path']}` | {d['doc_type']} | {d['date'] or '-'} | "
          f"{d['authority']} | {_cell(' '.join(d['warnings']))} |")
    w("\nAuthority tiers (used to resolve conflicts): 3 = formal decision (meeting minutes), "
      "2 = stakeholder input (interview, survey, e-mail), 1 = draft / background material. "
      "Within the same tier the more recent document wins.\n")

    w("## 3. Requirements overview\n")
    w("| Area | Name | Must | Should | Could | Total |\n|---|---|---|---|---|---|")
    for a in state["areas"]:
        ar = [r for r in reqs if r["area"] == a["code"]]
        if ar:
            c = {p: sum(r["priority"] == p for r in ar) for p in PRIORITY_SCALE}
            w(f"| {a['code']} | {a['name']} | {c['Must']} | {c['Should']} | {c['Could']} | {len(ar)} |")
    w(f"| | **Total** | {sum(r['priority'] == 'Must' for r in reqs)} | "
      f"{sum(r['priority'] == 'Should' for r in reqs)} | "
      f"{sum(r['priority'] == 'Could' for r in reqs)} | **{len(reqs)}** |\n")

    w("## 4. Requirements\n")
    for i, a in enumerate(state["areas"], 1):
        ar = [r for r in reqs if r["area"] == a["code"]]
        if not ar:
            continue
        w(f"### 4.{i} {a['name']} ({a['code']})\n")
        w(f"{a['description']}\n")
        for r in ar:
            w(f"#### {r['id']}: {r['name']}\n")
            w(f"**Priority:** {r['priority']} - {r['priority_rationale']}  ")
            if r.get("priority_evidence"):
                w(f"**Priority evidence:** {'; '.join(r['priority_evidence'])}  ")
            w(f"**Sources:** {', '.join(r['sources'])}" + ("  " if r["id"] in oi_of else "\n"))
            if r["id"] in oi_of:
                w(f"**Open issues:** {', '.join(oi_of[r['id']])} (see Section 7)\n")
            w(f"{r['description']}\n")
            w("<details><summary>Evidence</summary>\n")
            for s, q in r["evidence"].items():
                mark = "" if r["evidence_verified"][s] else " *(quote not found verbatim in source)*"
                w(f"- **{s}** `{docs[s]['path']}`: \"{_cell(q)}\"{mark}")
            w("\n</details>\n")

    w("## 5. Traceability matrix\n")
    w("| Document | Requirements derived |\n|---|---|")
    for d in docs.values():
        ids = [r["id"] for r in reqs if d["doc_id"] in r["sources"]]
        w(f"| {d['doc_id']} `{d['path']}` | {', '.join(ids) or '-'} |")
    w("")

    w("## 6. Blacklist (discarded requirements)\n")
    w("Requirements identified in the sources but not included in the specification because they "
      "are conflicting, superseded, nonsensical or out of scope.\n")
    if blacklist:
        w("| ID | Name | Original statement | Sources | Discarded at | Reason |\n|---|---|---|---|---|---|")
        for b in blacklist:
            w(f"| {b['id']} | {_cell(b['name'])} | {_cell(b['statement'])} | "
              f"{', '.join(b['sources'])} | {b['stage']} | {_cell(b['reason'])} |")
    else:
        w("*No requirements were discarded.*")
    w("")
    if state.get("merged_duplicates"):
        w("### 6.1 Merged duplicates\n")
        w("Requirements merged into another one because they express the same need. Their "
          "sources are attached to the requirement they were merged into; where both had "
          "distinct details, the texts were fused so that no detail is lost.\n")
        w("| Removed | Merged into | Explanation |\n|---|---|---|")
        for m in state["merged_duplicates"]:
            w(f"| {m['removed_id']} {_cell(m['name'])} | {m['kept_id']} | {_cell(m['explanation'])} |")
        w("")

    w("## 7. Open issues\n")
    w("Pairs of requirements that pull in different directions but were not confirmed as "
      "irreconcilable by the independent verifier. Both requirements are kept; stakeholders "
      "should clarify the listed point before design. Explanations may mention identifiers "
      "of requirements that were later merged into the listed ones (see Section 6.1).\n")
    if open_issues:
        w("| ID | Requirements | Origin | What needs clarification |\n|---|---|---|---|")
        for t in open_issues:
            reqs_txt = "; ".join(f"{x} {n}" for x, n in zip(t["ids"], t["names"]))
            w(f"| {t['oid']} | {_cell(reqs_txt)} | {t['source']} | {_cell(t['explanation'])} |")
    else:
        w("*No open issues.*")
    w("")

    w("## 8. Generation report\n")
    w("| Role | Model | LLM calls | Answers reused from cache |\n|---|---|---|---|")
    for role, model in MODELS.items():
        w(f"| {role} | {model} | {CALLS.get(role, 0)} | {CACHED.get(role, 0)} |")
    w("")
    unverified = sum(not c["quote_verified"] for c in state["candidates"])
    w(f"- Candidates extracted: {len(state['candidates'])} valid, "
      f"{len(state.get('rejected', []))} rejected by the extractor")
    w(f"- Quote verification: {len(state['candidates']) - unverified} of "
      f"{len(state['candidates'])} candidate quotes found in the cited source document")
    w(f"- Review rounds: {len(state.get('critic_history', []))}")
    for h in state.get("critic_history", []):
        w(f"  - Round {h['revision']}: {'passed' if h['passed'] else 'revisions requested'} "
          f"({h['issues']} issues) - {_cell(h['summary'])}")
    if gaps := state.get("coverage_gaps"):
        w(f"- Unresolved coverage gaps: {', '.join(c for v in gaps.values() for c in v)}")
    fidelity = [x for v in state.get("fidelity_gaps", {}).values() for x in v]
    w(f"- Merge-fidelity warnings remaining after the last review round: {len(fidelity)}")
    for x in fidelity:
        w(f"  - {_cell(x)}")
    for e in state.get("errors", []):
        w(f"- Error: {_cell(e)}")
    w("")

    out_dir = Path(state["output_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)
    md_path = out_dir / "requirements.md"
    md_path.write_text("\n".join(out), encoding="utf-8")
    (out_dir / "requirements.json").write_text(json.dumps({
        "documents": [{k: v for k, v in d.items() if k != "text"} for d in docs.values()],
        "areas": state["areas"], "glossary": state["glossary"],
        "requirements": reqs, "blacklist": blacklist,
        "merged_duplicates": state.get("merged_duplicates", []),
        "open_issues": open_issues,
        "critic_history": state.get("critic_history", []),
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"[render] {len(reqs)} requirements, {len(blacklist)} blacklisted -> {md_path}")
    return {}
