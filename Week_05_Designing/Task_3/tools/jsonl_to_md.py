"""Convert a Claude Code session JSONL into a readable Markdown transcript (read-only on the source).

Usage: python -I jsonl_to_md.py <session.jsonl> <output.md> <repo_root> ["<title>"]
"""
import json
import re
import sys

src, dst, repo = sys.argv[1], sys.argv[2], sys.argv[3].replace("\\", "/").rstrip("/")
title = sys.argv[4] if len(sys.argv) > 4 else "Transcript"

IDE_RE = re.compile(r"^<ide_(selection|opened_file)>(.*?)</ide_\1>", re.S)


def rel(path):
    p = str(path).replace("\\", "/")
    low = p.lower()
    i = low.find(repo.lower())
    return p[i + len(repo) + 1:] if i >= 0 else p


def tool_line(b, results):
    name, inp = b.get("name"), b.get("input", {}) or {}
    if "file_path" in inp:
        arg = rel(inp["file_path"])
    elif name == "Bash" or name == "PowerShell":
        arg = inp.get("description") or inp.get("command", "")[:80]
    elif "pattern" in inp:
        arg = inp["pattern"]
    elif "query" in inp:
        arg = inp["query"]
    elif "skill" in inp:
        arg = inp["skill"]
    else:
        arg = ", ".join(f"{k}" for k in inp)[:80]
    arg = " ".join(str(arg).split())
    res = results.get(b.get("id"))
    status = "ok"
    if res is not None and res.get("is_error"):
        c = res.get("content")
        txt = c if isinstance(c, str) else " ".join(x.get("text", "") for x in (c or []) if isinstance(x, dict))
        status = "error: " + " ".join(txt.split())[:100]
    return f"> [tool: {name} {arg} → {status}]"


entries = []
with open(src, encoding="utf-8") as f:
    for line in f:
        d = json.loads(line)
        if d.get("type") in ("user", "assistant") and not d.get("isSidechain"):
            entries.append(d)

results = {}
for d in entries:
    c = d["message"].get("content")
    if d["type"] == "user" and isinstance(c, list):
        for b in c:
            if b.get("type") == "tool_result":
                results[b.get("tool_use_id")] = b

out, user_count, seen = [], 0, set()
current = None  # "user" / "assistant"
for d in entries:
    c = d["message"].get("content")
    blocks = [{"type": "text", "text": c}] if isinstance(c, str) else (c or [])
    if d["type"] == "user":
        if d.get("isMeta") or all(b.get("type") == "tool_result" for b in blocks):
            continue
        parts = []
        for b in blocks:
            if b.get("type") == "image":
                parts.append("> [image attached: screenshot]")
            elif b.get("type") == "text":
                t = b["text"]
                m = IDE_RE.match(t.strip())
                while m:
                    parts.append(f"> [IDE context: {' '.join(m.group(2).split())[:160]}]")
                    t = t.strip()[m.end():]
                    m = IDE_RE.match(t.strip())
                if t.strip():
                    parts.append(t.strip("\n"))
        if not parts:
            continue
        user_count += 1
        out.append(f"\n## User\n")
        out.append("\n\n".join(parts))
        current = "user"
    else:
        key = (d["message"].get("id"), json.dumps(blocks, sort_keys=True)[:200])
        if key in seen:
            continue
        seen.add(key)
        parts = []
        for b in blocks:
            if b.get("type") == "text" and b["text"].strip():
                parts.append(b["text"].strip("\n"))
            elif b.get("type") == "tool_use":
                parts.append(tool_line(b, results))
        if not parts:
            continue
        if current != "assistant":
            out.append("\n## Assistant\n")
            current = "assistant"
        out.append("\n\n".join(parts))

header = (
    f"# {title}\n\n"
    f"Source: `{src}` (Claude Code session log, read-only).\n"
    "Generated by a script: user and assistant text kept verbatim and in order; tool calls shortened to "
    "one line each (`[tool: …]`, with result status); internal reasoning blocks, tool outputs and "
    "automatic system reminders omitted; IDE context (selected lines / opened file) shortened to one line.\n"
)
with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write(header + "\n".join(out) + "\n")
print("user messages:", user_count)
